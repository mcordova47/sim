// Generates outfit sprites from art/outfits.json (issue 158). Each outfit is a small data entry: a body
// template (an existing hand-drawn outfit, 12 files), a palette for the torso with a rule per facing, a
// recolour for the legs, and optional hand-drawn rows laid on top. The output is ordinary `.sprite` files
// in art/src, so the game and the sprite checks do not change. Files carry a GENERATED header; running
// again with the same data rewrites nothing. `npm run sprites` runs this first.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";
import { root } from "./sprite-lib.mjs";

const srcDir = join(root, "art", "src");
export const DIRS = ["down", "up", "left", "right"];
export const FILES = DIRS.flatMap((d) => [`idle-${d}`, `walk-${d}-1`, `walk-${d}-2`]);
export const HEADER_MARK = "GENERATED by scripts/outfits.mjs";

// Torso rules. `x` is the column, [x0, x1] the torso's run in this row, `k` the distance from the front edge
// (side views), `last` whether this is the torso's last row. Each returns "outer", "shade" or "inner".
export const RULES = {
  // Open jacket or cardigan over a shirt. Down: shirt in the middle four columns, a shade column either side.
  // Up: a shade seam down the middle. Side: the front column is shirt, then a shade column, then the jacket.
  "open-front": ({ dir, x, x0, x1, k, last }) => {
    const mid = (x0 + x1) / 2;
    if (dir === "down") { const d = Math.abs(x - mid); return d <= 1.5 ? "inner" : d <= 2.5 ? "shade" : "outer"; }
    if (dir === "up") return Math.abs(x - mid) <= 0.5 ? "shade" : "outer";
    return last ? (k === 0 ? "shade" : "outer") : k === 0 ? "inner" : k === 1 ? "shade" : "outer";
  },
  // One solid colour.
  solid: () => "outer",
};

const dirOf = (file) => DIRS.find((d) => file.includes(d));
const bodyRows = (text) => text.split("\n").filter((l) => l && !l.startsWith("#") && !l.startsWith("size"));

// The 12 sprites of one outfit as { file: text }. `read` returns a template file's text.
export function generateOutfit(def, read) {
  const out = {};
  for (const f of FILES) {
    const rows = bodyRows(read(`${def.template}-${f}`));
    const dir = dirOf(f);
    const torsoRows = rows.map((r, i) => (/[ef]/.test(r) ? i : -1)).filter((i) => i >= 0);
    const lastTorso = torsoRows[torsoRows.length - 1];
    const ruleName = def.torso.facing?.[dir] ?? def.torso.rule; // a facing can use its own rule (a plain back)
    const rule = RULES[ruleName];
    if (!rule) throw new Error(`${def.id}: unknown torso rule ${ruleName}`);
    const pal = def.torso;
    const made = rows.map((row, i) => {
      const chars = [...row];
      if (torsoRows.includes(i)) {
        const cols = chars.map((c, x) => (c === "e" || c === "f" ? x : -1)).filter((x) => x >= 0);
        const x0 = cols[0], x1 = cols[cols.length - 1];
        for (const x of cols) {
          const k = dir === "right" ? x1 - x : x - x0;
          chars[x] = pal[rule({ dir, x, x0, x1, k, last: i === lastTorso })];
        }
      } else if (i > lastTorso) {
        for (const [x, c] of chars.entries()) if (def.legs?.[c]) chars[x] = def.legs[c];
      }
      return chars.join("");
    });
    for (const [row, text] of Object.entries(def.overlays?.[f] ?? {})) {
      if ([...text].length !== 16) throw new Error(`${def.id} ${f} row ${row}: overlay is not 16 wide`);
      made[Number(row)] = text;
    }
    out[`${def.prefix}-${f}`] =
      `# ${HEADER_MARK} from art/outfits.json (${def.describe}); do not edit by hand, change the data and run npm run sprites. Same pose as ${def.template}-${f}. 16x16.\n` +
      `size: 16x16\n${made.join("\n")}\n`;
  }
  return out;
}

export const loadOutfits = () => JSON.parse(readFileSync(join(root, "art", "outfits.json"), "utf8")).outfits;
const readTemplate = (name) => readFileSync(join(srcDir, `${name}.sprite`), "utf8");

// Writes the files that differ; returns the names written.
export function writeOutfits() {
  const written = [];
  for (const def of loadOutfits()) {
    for (const [name, text] of Object.entries(generateOutfit(def, readTemplate))) {
      const path = join(srcDir, `${name}.sprite`);
      if (existsSync(path) && readFileSync(path, "utf8") === text) continue;
      writeFileSync(path, text);
      written.push(name);
    }
  }
  return written;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const w = writeOutfits();
  console.log(w.length ? `Generated ${w.length} outfit sprite(s) from art/outfits.json` : "Outfit sprites are up to date");
}
