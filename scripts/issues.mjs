export const STATUSES = ['todo', 'in-progress', 'blocked', 'review', 'done'];
export const REQUIRED = ['id', 'title', 'status', 'owner', 'depends_on'];
// Optional keys. Stage 1 writes and checks `short` and `note`; the others are
// named in the design (section 4.1) for later stages and are accepted, not checked.
export const OPTIONAL = [
  'short', 'note',
  'summary', 'changelog', 'kind', 'thread', 'area', 'needs', 'decisions', 'unverified',
  'links', 'docs', 'superseded_by',
];
// Closed sets (design sections 4.1 and 4.3). The pill on a card is exactly one of these words.
export const KINDS = ['design', 'build', 'research', 'fix', 'umbrella', 'chore'];
export const NEEDS_WHO = ['marc', 'planner', 'agent', 'other'];
export const NEEDS_KIND = ['decide', 'do', 'try', 'review', 'wait'];
export const DECISION_STATUS = ['open', 'answered', 'defaulted', 'dropped'];
export const SUMMARY_LIMIT = 120;
const DATE_PATTERN = /^\d{4}-\d{2}-\d{2}$/;
const ID_PATTERN = /^\d{3}[a-z]?$/;
const FILE_PATTERN = /^(\d{3}[a-z]?)-.+\.md$/;

export const TABLE_START =
  '<!-- issues:table:start (generated by `npm run issues`; do not edit by hand) -->';
export const TABLE_END = '<!-- issues:table:end -->';

// Parse one issue file. Never throws: problems come back as `errors`.
// Every scalar is read as a string (the failsafe schema), so `id: 007` stays
// "007" and `id: 010` is not an octal number.
export function parseIssue(name, text) {
  const errors = [];
  const warnings = [];
  const err = (line, message) => errors.push({ file: name, line, message });
  const lines = text.replace(/\r\n/g, '\n').split('\n');
  const issue = { name, errors, warnings, fm: {}, lines: {}, headings: [] };

  if (lines[0] !== '---') {
    err(1, 'The file must start with a front matter block (a line of three dashes).');
    return issue;
  }
  const end = lines.indexOf('---', 1);
  if (end === -1) {
    err(1, 'The front matter block never ends (no closing line of three dashes).');
    return issue;
  }
  const fmLines = lines.slice(1, end);
  issue.body = lines.slice(end + 1).join('\n');
  issue.fmLines = fmLines;
  for (let i = 0; i < fmLines.length; i++) {
    const m = fmLines[i].match(/^([A-Za-z_][\w-]*):/);
    if (m && !(m[1] in issue.lines)) issue.lines[m[1]] = i + 2; // file line, 1-based
  }

  const lc = new LineCounter();
  const doc = parseDocument(fmLines.join('\n'), { schema: 'failsafe', lineCounter: lc });
  for (const e of doc.errors) {
    const line = (e.linePos && e.linePos[0] ? e.linePos[0].line : 1) + 1;
    err(line, `The front matter is not valid YAML: ${e.message.split('\n')[0]}`);
  }
  if (doc.errors.length) return issue;
  const fm = doc.toJS();
  if (fm === null || typeof fm !== 'object' || Array.isArray(fm)) {
    err(2, 'The front matter must be a list of "key: value" lines.');
    return issue;
  }
  issue.fm = fm;

  let inFence = false;
  const seen = new Map();
  for (let i = end + 1; i < lines.length; i++) {
    if (/^\s*(```|~~~)/.test(lines[i])) inFence = !inFence;
    const m = !inFence && lines[i].match(/^(#{2,3}) +(.+?) *$/);
    if (m) {
      const key = `${m[1]} ${m[2]}`;
      issue.headings.push({ level: m[1].length, text: m[2], line: i + 1 });
      if (seen.has(key)) {
        warnings.push({
          file: name, line: i + 1,
          message: `The heading "${m[2]}" appears twice (first on line ${seen.get(key)}).`,
        });
      } else seen.set(key, i + 1);
    }
  }
  return issue;
}

const isString = (v) => typeof v === 'string';

// A repo-relative path to a Markdown file (an optional #anchor is allowed where `anchor` is true).
export const isDocPath = (x, anchor = false) => {
  const [p, ...rest] = String(x).split('#');
  if (rest.length && !anchor) return false;
  if (rest.length > 1 || (rest.length && !/^[\w.-]+$/.test(rest[0]))) return false;
  return /^[\w][\w./-]*\.md$/.test(p) && !p.includes('..') && !p.includes('//');
};
const validDate = (v) => isString(v) && DATE_PATTERN.test(v) && !Number.isNaN(Date.parse(v));

// Parsed doc questions are named q1, q2 ...; hand-written ones must not use that shape.
const DECISION_ID = /^[a-z][a-z0-9-]*$/;
const PARSED_ID = /^q\d+$/;

function checkDecisions(issue, err) {
  const list = issue.fm.decisions;
  const flow = 'Each decision has an id like d1, a q (the question) and a status.';
  if (!Array.isArray(list) || !list.every((n) => n && typeof n === 'object' && !Array.isArray(n))) {
    err('decisions', `decisions must be a list of entries. ${flow}`);
    return;
  }
  const seen = new Set();
  const known = ['id', 'q', 'options', 'recommendation', 'status', 'answer', 'by', 'who', 'on', 'doc', 'note'];
  list.forEach((d, i) => {
    const at = list.length > 1 ? ` (entry ${i + 1}${isString(d.id) ? `, ${d.id}` : ''})` : '';
    const bad = (m) => err('decisions', `decisions${at}: ${m}`);
    for (const k of Object.keys(d)) {
      if (!known.includes(k)) issue.warnings.push({ file: issue.name, line: issue.lines.decisions || 2, message: `decisions${at} has "${k}", which is not a field this tool knows.` });
    }
    if (!isString(d.id) || !DECISION_ID.test(d.id)) bad('id must be a short lowercase name like d1.');
    else if (PARSED_ID.test(d.id)) bad(`id ${d.id} is reserved for questions read from design docs; use d1, d2 ...`);
    else if (seen.has(d.id)) bad(`id ${d.id} is used twice in this issue.`);
    else seen.add(d.id);
    if (!isString(d.q) || d.q.trim() === '') bad('q must be the question, as one plain line.');
    if (!DECISION_STATUS.includes(d.status)) bad(`status "${d.status}" is not one of: ${DECISION_STATUS.join(', ')}.`);
    if ('who' in d && !NEEDS_WHO.includes(d.who)) bad(`who "${d.who}" is not one of: ${NEEDS_WHO.join(', ')}.`);
    if ('by' in d && !NEEDS_WHO.includes(d.by)) bad(`by "${d.by}" is not one of: ${NEEDS_WHO.join(', ')}.`);
    if ('on' in d && !validDate(d.on)) bad('on must be a date like 2026-11-15.');
    if ('options' in d && (!Array.isArray(d.options) || !d.options.every((o) => isString(o) && o.trim() !== ''))) bad('options must be a list of short labels, like ["Crisp", "Soft"].');
    for (const k of ['recommendation', 'answer', 'note']) {
      if (k in d && (!isString(d[k]) || d[k].trim() === '')) bad(`${k} must be one plain line of text.`);
    }
    if ('doc' in d && (!isString(d.doc) || !isDocPath(d.doc, true))) bad('doc must be a repo path to a Markdown file, with an optional #section, like docs/x-design.md#14-questions.');
    if (d.status === 'answered' || d.status === 'defaulted') {
      for (const k of ['answer', 'by', 'on']) if (!(k in d)) bad(`a ${d.status} decision needs ${k}.`);
    }
    if (d.status === 'open' && ('answer' in d || 'by' in d)) {
      issue.warnings.push({ file: issue.name, line: issue.lines.decisions || 2, message: `decisions${at} is open but has an answer; set its status to answered.` });
    }
  });
}

// Check one parsed issue by itself (no other files needed).
function checkOne(issue) {
  const { name, fm } = issue;
  const err = (key, message) =>
    issue.errors.push({ file: name, line: issue.lines[key] || 2, message });
  const fileMatch = name.match(FILE_PATTERN);
  if (!fileMatch) {
    issue.errors.push({
      file: name, line: 1,
      message: 'The file name must look like 117g-short-slug.md (three digits, an optional letter, a dash).',
    });
  }
  for (const key of REQUIRED) {
    if (!(key in fm)) err(key, `The front matter is missing "${key}".`);
  }
  for (const key of Object.keys(fm)) {
    if (!REQUIRED.includes(key) && !OPTIONAL.includes(key)) {
      issue.warnings.push({
        file: name, line: issue.lines[key] || 2,
        message: `"${key}" is not a field this tool knows. Check the spelling.`,
      });
    }
  }
  if ('id' in fm) {
    if (!isString(fm.id) || !ID_PATTERN.test(fm.id)) {
      err('id', `The id "${fm.id}" must be three digits with an optional lowercase letter, like 007 or 117g.`);
    } else if (fileMatch && fm.id !== fileMatch[1]) {
      err('id', `The id "${fm.id}" does not match the file name, which starts with ${fileMatch[1]}.`);
    }
    // Belt and braces: the raw text must agree, so a number-coerced id (7 for 007)
    // can never slip through another reader.
    const raw = (issue.fmLines.find((l) => /^id:/.test(l)) || '').replace(/^id:\s*/, '').replace(/^(["'])(.*)\1\s*$/, '$2').trim();
    if (fileMatch && raw !== fileMatch[1] && isString(fm.id) && ID_PATTERN.test(fm.id)) {
      err('id', `The id line reads "${raw}" but the file name starts with ${fileMatch[1]}.`);
    }
  }
  if ('title' in fm && (!isString(fm.title) || fm.title.trim() === '')) {
    err('title', 'The title must be a non-empty line of text.');
  }
  if ('status' in fm && !STATUSES.includes(fm.status)) {
    err('status', `The status "${fm.status}" is not one of: ${STATUSES.join(', ')}.`);
  }
  if ('owner' in fm && (!isString(fm.owner) || fm.owner.trim() === '')) {
    err('owner', 'The owner must be a non-empty line of text, like "claude" or "marc + claude".');
  }
  if ('depends_on' in fm) {
    const d = fm.depends_on;
    if (!Array.isArray(d) || !d.every(isString)) {
      err('depends_on', 'depends_on must be a list of ids in square brackets, like [006, 007a], or [] for none.');
    } else {
      for (const x of d) {
        if (!ID_PATTERN.test(x)) err('depends_on', `depends_on lists "${x}", which is not a valid id.`);
        if (x === fm.id) err('depends_on', 'An issue cannot depend on itself.');
      }
    }
  }
  for (const key of ['short', 'note', 'thread', 'superseded_by', 'summary']) {
    if (key in fm && (!isString(fm[key]) || fm[key].trim() === '')) {
      err(key, `"${key}" must be a non-empty line of text.`);
    }
  }

  if ('summary' in fm && isString(fm.summary) && fm.summary.trim() !== '' && fm.summary.length > SUMMARY_LIMIT) {
    issue.warnings.push({
      file: name, line: issue.lines.summary || 2,
      message: `The summary is ${fm.summary.length} characters; about ${SUMMARY_LIMIT} reads best as a headline.`,
    });
  }
  if ('changelog' in fm) {
    const p = changelogProblem(fm.changelog);
    if (p) err('changelog', p);
  }
  if ('kind' in fm && !KINDS.includes(fm.kind)) {
    err('kind', `The kind "${fm.kind}" is not one of: ${KINDS.join(', ')}.`);
  }
  if ('unverified' in fm) {
    const u = fm.unverified;
    if (!Array.isArray(u) || !u.every((x) => isString(x) && x.trim() !== '')) {
      err('unverified', 'unverified must be a list of one-line texts, like ["Safari behaviour"].');
    }
  }
  if ('docs' in fm) {
    const d = fm.docs;
    if (!Array.isArray(d) || !d.every((x) => isString(x) && isDocPath(x))) {
      err('docs', 'docs must be a list of repo paths to Markdown files, like [docs/photo-gallery-design.md]. No web addresses.');
    }
  }
  if ('decisions' in fm) checkDecisions(issue, err);
  if ('needs' in fm) {
    const list = fm.needs;
    const flow = 'Write each as one line: needs: [{who: marc, kind: try, why: "Run it once", since: 2026-11-15}].';
    if (!Array.isArray(list) || !list.every((n) => n && typeof n === 'object' && !Array.isArray(n))) {
      err('needs', `needs must be a list of entries with who, kind, why and since. ${flow}`);
    } else {
      list.forEach((n, i) => {
        const at = list.length > 1 ? ` (entry ${i + 1})` : '';
        for (const k of Object.keys(n)) {
          if (!['who', 'kind', 'why', 'since', 'on'].includes(k)) {
            issue.warnings.push({ file: name, line: issue.lines.needs || 2, message: `needs${at} has "${k}", which is not a field this tool knows.` });
          }
        }
        if (!NEEDS_WHO.includes(n.who)) err('needs', `needs${at}: who "${n.who}" is not one of: ${NEEDS_WHO.join(', ')}.`);
        if (!NEEDS_KIND.includes(n.kind)) err('needs', `needs${at}: kind "${n.kind}" is not one of: ${NEEDS_KIND.join(', ')}.`);
        if (!isString(n.why) || n.why.trim() === '') err('needs', `needs${at}: why must be one plain line of text.`);
        if (!isString(n.since) || !DATE_PATTERN.test(n.since) || Number.isNaN(Date.parse(n.since))) err('needs', `needs${at}: since must be a date like 2026-11-15.`);
        if (n.kind === 'wait' && (!isString(n.on) || n.on.trim() === '')) err('needs', `needs${at}: a wait entry says what it waits on, with on: "...".`);
      });
    }
  }
}

// The thread an id belongs to by default: the id without its trailing letter.
export const defaultThread = (id) => (/^\d{3}[a-z]$/.test(id) ? id.slice(0, 3) : null);

// Parse and validate a set of files [{name, text}]. Returns { issues, errors, warnings }.
export function analyze(files, { docExists = null } = {}) {
  const issues = files.map((f) => parseIssue(f.name, f.text));
  for (const issue of issues) {
    if (!issue.errors.length) checkOne(issue);
  }
  const errors = [];
  const warnings = [];

  const byId = new Map();
  for (const issue of issues) {
    const id = issue.fm.id;
    if (!isString(id) || issue.errors.length) continue;
    if (byId.has(id)) {
      issue.errors.push({
        file: issue.name, line: issue.lines.id || 2,
        message: `The id ${id} is also used by ${byId.get(id).name}.`,
      });
    } else byId.set(id, issue);
  }
  const good = issues.filter((i) => !i.errors.length);

  for (const issue of good) {
    const { fm, name } = issue;
    const at = (key) => ({ file: name, line: issue.lines[key] || 2 });
    for (const dep of fm.depends_on) {
      if (ID_PATTERN.test(dep) && !byId.has(dep)) {
        issue.errors.push({ ...at('depends_on'), message: `depends_on lists ${dep}, which does not exist.` });
      }
    }
    for (const key of ['thread', 'superseded_by']) {
      if (isString(fm[key]) && fm[key].trim() !== '') {
        if (!byId.has(fm[key])) {
          issue.errors.push({ ...at(key), message: `${key} names ${fm[key]}, which does not exist.` });
        } else if (fm[key] === fm.id) {
          issue.errors.push({ ...at(key), message: `${key} cannot name the issue itself.` });
        } else if (key === 'thread') {
          const t = byId.get(fm.thread);
          const up = t.fm.thread || (defaultThread(t.fm.id) && byId.has(defaultThread(t.fm.id)) ? defaultThread(t.fm.id) : null);
          if (up) {
            issue.errors.push({ ...at(key), message: `thread names ${fm.thread}, which is itself part of thread ${up}; name the root of the thread (${up}).` });
          }
        }
      }
    }
    if (docExists) {
      const paths = [...(Array.isArray(fm.docs) ? fm.docs : []), ...(Array.isArray(fm.decisions) ? fm.decisions.map((d) => d && isString(d.doc) ? d.doc.split('#')[0] : null) : [])];
      for (const p of paths) {
        if (isString(p) && isDocPath(p) && !docExists(p)) {
          issue.errors.push({ ...at('docs' in fm ? 'docs' : 'decisions'), message: `${p} is named here but does not exist.` });
        }
      }
    }
    const parent = defaultThread(fm.id);
    if (parent && !('thread' in fm) && !byId.has(parent)) {
      issue.warnings.push({ ...at('id'), message: `${fm.id} looks like part of thread ${parent}, but there is no issue ${parent}.` });
    }
  }

  // Loops: depends_on, and superseded_by.
  const findLoops = (label, next) => {
    const state = new Map(); // id -> 1 visiting, 2 done
    const walk = (id, stack) => {
      state.set(id, 1);
      for (const n of next(id)) {
        if (!byId.has(n)) continue;
        if (state.get(n) === 1) {
          const loop = [...stack.slice(stack.indexOf(n)), n];
          const issue = byId.get(loop[0]);
          issue.errors.push({
            file: issue.name, line: issue.lines[label] || 2,
            message: `${label} goes round in a loop: ${loop.join(' -> ')}.`,
          });
        } else if (!state.has(n)) walk(n, [...stack, n]);
      }
      state.set(id, 2);
    };
    for (const id of byId.keys()) if (!state.has(id)) walk(id, [id]);
  };
  findLoops('depends_on', (id) => (Array.isArray(byId.get(id).fm.depends_on) ? byId.get(id).fm.depends_on : []));
  findLoops('superseded_by', (id) => (byId.get(id).fm.superseded_by ? [byId.get(id).fm.superseded_by] : []));

  // Warnings that need other files.
  const members = new Map(); // root id -> member issues
  for (const issue of good) {
    const root = issue.fm.thread || defaultThread(issue.fm.id);
    if (root && byId.has(root)) {
      if (!members.has(root)) members.set(root, []);
      members.get(root).push(issue);
    }
  }
  for (const [root, list] of members) {
    const r = byId.get(root);
    if (r.fm.status !== 'done') continue;
    const open = list.filter((m) => m.fm.status !== 'done' && !m.fm.superseded_by);
    if (open.length) {
      r.warnings.push({
        file: r.name, line: r.lines.status || 2,
        message: `${root} is done, but ${open.map((m) => m.fm.id).join(', ')} ${open.length === 1 ? 'is' : 'are'} not.`,
      });
    }
  }
  for (const issue of good) {
    const t = issue.fm.superseded_by && byId.get(issue.fm.superseded_by);
    if (t && !['done', 'todo'].includes(issue.fm.status)) {
      issue.warnings.push({
        file: issue.name, line: issue.lines.superseded_by || 2,
        message: `${issue.fm.id} is superseded by ${t.fm.id} but is ${issue.fm.status}; expected done or todo.`,
      });
    }
  }

  for (const issue of good) {
    const { fm } = issue;
    // Only for work being done now: the old backlog is filled in by the backfill (issue 132).
    if (!isString(fm.summary) && ['in-progress', 'review'].includes(fm.status)) {
      issue.warnings.push({ file: issue.name, line: 2, message: `${fm.id} has no summary yet; a one-line headline helps the pages.` });
    }
    if (fm.status === 'done' && Array.isArray(fm.needs) && fm.needs.length) {
      issue.warnings.push({ file: issue.name, line: issue.lines.needs || 2, message: `${fm.id} is done but still lists needs; remove an entry when it is resolved (a post-merge check may be fine).` });
    }
  }

  for (const issue of issues) {
    errors.push(...issue.errors);
    warnings.push(...issue.warnings);
  }
  const order = (a, b) => (a.file < b.file ? -1 : a.file > b.file ? 1 : a.line - b.line);
  errors.sort(order);
  warnings.sort(order);
  return { issues: good.filter((i) => !i.errors.length), errors, warnings };
}

