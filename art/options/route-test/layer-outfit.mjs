// Issue 156, art-route test (not shipped): the recolor/layer route for ONE outfit, casual option B
// (tan open cardigan over a white tee). It takes the shipped casual sprites as the body template
// (the sweater is the run of `e`/`f` in the torso rows; hands `a`, jeans `h` and the head stay),
// and paints the torso by a small rule per facing, with no hand-drawing:
//   down:  tee in the middle four columns, a shade column each side of it, cardigan beyond
//   up:    cardigan with a shade seam down the middle
//   side:  the front-most column is tee, then a shade column, then cardigan
// Run: node art/options/route-test/layer-outfit.mjs   (writes ./layered/*.sprite); `... l m layered-putty` writes a putty-grey cardigan to ./layered-putty
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const src = join(here, "..", "..", "src");
// Optional: node layer-outfit.mjs <cardigan> <shade> <out-folder>, for a different palette letter (one constant, no redrawing).
const [argC, argS, argOut] = process.argv.slice(2);
const CARDIGAN = argC ?? "9", SHADE = argS ?? "8", TEE = "6";
const OUT = argOut ?? "layered";
const FILES = [];
for (const dir of ["down", "up", "left", "right"]) {
  FILES.push(`idle-${dir}`, `walk-${dir}-1`, `walk-${dir}-2`);
}
mkdirSync(join(here, OUT), { recursive: true });
for (const f of FILES) {
  const lines = readFileSync(join(src, `player-casual-${f}.sprite`), "utf8").split("\n");
  const body = lines.filter((l) => l && !l.startsWith("#") && !l.startsWith("size"));
  const dir = f.includes("down") ? "down" : f.includes("up") ? "up" : f.includes("left") ? "left" : "right";
  const rows = body.map((r, i) => (/[ef]/.test(r) ? i : -1)).filter((i) => i >= 0);
  const last = rows[rows.length - 1];
  const out = body.map((row, i) => {
    if (!rows.includes(i)) return row;
    const chars = [...row];
    const cols = chars.map((c, x) => (c === "e" || c === "f" ? x : -1)).filter((x) => x >= 0);
    const x0 = cols[0], x1 = cols[cols.length - 1], mid = (x0 + x1) / 2;
    for (const x of cols) {
      let c = CARDIGAN;
      if (dir === "down") { const d = Math.abs(x - mid); c = d <= 1.5 ? TEE : d <= 2.5 ? SHADE : CARDIGAN; }
      else if (dir === "up") c = Math.abs(x - mid) <= 0.5 ? SHADE : CARDIGAN;
      else {
        const k = dir === "right" ? x1 - x : x - x0; // 0 at the front edge
        c = i === last ? (k === 0 ? SHADE : CARDIGAN) : k === 0 ? TEE : k === 1 ? SHADE : CARDIGAN;
      }
      chars[x] = c;
    }
    return chars.join("");
  });
  writeFileSync(
    join(here, OUT, `player-casual-cardigan-${f}.sprite`),
    `# Player, casual option B (tan open cardigan over a white tee, jeans), same pose as player-${f}. Generated by layer-outfit.mjs (issue 156 art-route test). 16x16.\nsize: 16x16\n${out.join("\n")}\n`,
  );
}
console.log(`wrote ${FILES.length} sprites`);
